  const isRotated = [5, 6, 7, 8].includes(metadata.orientation);
  const displayWidth = isRotated ? metadata.height : metadata.width;
  const displayHeight = isRotated ? metadata.width : metadata.height;
  const widths = Array.from(new Set(targetWidths.filter((width) => width < displayWidth).concat(displayWidth))).sort((a, b) => a - b);
