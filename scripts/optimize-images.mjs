/* global console */
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = path.join(root, 'src/images');
const outputRoot = path.join(root, 'public/optimized-images');
const generatedRoot = path.join(root, 'src/generated');
const generatedFile = path.join(generatedRoot, 'optimized-image-map.js');
const extensions = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const targetWidths = [480, 768, 1280, 1600, 1920];
const manifest = {};
let sourceBytesTotal = 0;
let fullWidthWebpBytesTotal = 0;
let variantBytesTotal = 0;

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute));
    else if (extensions.has(path.extname(entry.name).toLowerCase())) files.push(absolute);
  }
  return files;
}

async function assetKey(relativePath, file) {
  const normalized = relativePath.split(path.sep).join('/');
  const pathDigest = createHash('sha1').update(normalized).digest('hex').slice(0, 8);
  const contentDigest = createHash('sha1').update(await fs.readFile(file)).digest('hex').slice(0, 10);
  const basename = path.basename(normalized, path.extname(normalized))
    .normalize('NFKD')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
  return pathDigest + '-' + contentDigest + '-' + basename;
}

await fs.rm(outputRoot, { recursive: true, force: true });
await fs.mkdir(outputRoot, { recursive: true });
await fs.mkdir(generatedRoot, { recursive: true });

const sourceFiles = await walk(sourceRoot);
if (sourceFiles.length === 0) {
  throw new Error('No supported school image assets were found in src/images.');
}

for (const file of sourceFiles) {
  const relativePath = path.relative(sourceRoot, file);
  const key = relativePath.split(path.sep).join('/');
  sourceBytesTotal += (await fs.stat(file)).size;

  const metadata = await sharp(file, { failOn: 'none' }).metadata();
  if (!metadata.width || !metadata.height) {
    console.warn('Skipping image with unreadable dimensions: ' + key);
    continue;
  }

  const isRotated = [5, 6, 7, 8].includes(metadata.orientation);
  const displayWidth = isRotated ? metadata.height : metadata.width;
  const displayHeight = isRotated ? metadata.width : metadata.height;
  const widths = Array.from(
    new Set(targetWidths.filter((width) => width < displayWidth).concat(displayWidth))
  ).sort((a, b) => a - b);
  const name = await assetKey(relativePath, file);
  const variants = [];

  for (const width of widths) {
    const output = path.join(outputRoot, name + '-' + width + '.webp');
    const result = await sharp(file, { failOn: 'none' })
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 78, effort: 5, smartSubsample: true })
      .toFile(output);

    variantBytesTotal += result.size;
    variants.push({
      width,
      url: '/optimized-images/' + name + '-' + width + '.webp',
      size: result.size,
    });
  }

  const largest = variants[variants.length - 1];
  fullWidthWebpBytesTotal += largest.size;
  manifest[key] = {
    src: largest.url,
    srcSet: variants.map((item) => item.url + ' ' + item.width + 'w').join(', '),
    width: displayWidth,
    height: displayHeight,
  };
}

const moduleSource =
  '// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n' +
  'const optimizedImageMap = ' + JSON.stringify(manifest, null, 2) + ';\n\n' +
  'export default optimizedImageMap;\n';
await fs.writeFile(generatedFile, moduleSource);

const reduction = sourceBytesTotal > 0
  ? ((sourceBytesTotal - fullWidthWebpBytesTotal) / sourceBytesTotal) * 100
  : 0;
const sizeChange = reduction >= 0
  ? reduction.toFixed(1) + '% smaller'
  : Math.abs(reduction).toFixed(1) + '% larger';
const toMb = (bytes) => (bytes / 1024 / 1024).toFixed(2) + ' MB';

console.log('Optimized ' + Object.keys(manifest).length + ' images into responsive WebP variants.');
console.log(
  'Full-resolution images: ' + toMb(sourceBytesTotal) + ' source -> ' +
  toMb(fullWidthWebpBytesTotal) + ' WebP (' + sizeChange + ').'
);
console.log('All responsive WebP variants total: ' + toMb(variantBytesTotal) + '.');
